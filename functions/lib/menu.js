export async function ensureMenu(db) {
  await db
    .prepare(
      'CREATE TABLE IF NOT EXISTS site_menu (id INTEGER PRIMARY KEY AUTOINCREMENT, section TEXT DEFAULT \'\', title TEXT NOT NULL, body TEXT DEFAULT \'\', sort INTEGER NOT NULL DEFAULT 0, created_at INTEGER NOT NULL DEFAULT 0)'
    )
    .run();
  const row = await db.prepare('SELECT COUNT(*) AS n FROM site_menu').first();
  if (row && Number(row.n) > 0) return;
  const now = Math.floor(Date.now() / 1000);
  for (let i = 0; i < DEFAULTS.length; i++) {
    const d = DEFAULTS[i];
    await db
      .prepare('INSERT INTO site_menu (section, title, body, sort, created_at) VALUES (?, ?, ?, ?, ?)')
      .bind(d.section, d.title, d.body, i + 1, now)
      .run();
  }
}

export async function listMenu(db) {
  await ensureMenu(db);
  const { results } = await db.prepare('SELECT id, section, title, body, sort FROM site_menu ORDER BY sort ASC, id ASC').all();
  return results || [];
}

export function publicItem(row) {
  return {
    id: row.id,
    section: String(row.section || '').trim(),
    title: String(row.title || '').trim(),
    body: String(row.body || ''),
  };
}
